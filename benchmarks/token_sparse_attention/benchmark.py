"""Compare BF16 token-sparse PrimTS D256 with FlashMLA D512 on one GPU.

Each backend runs in a fresh subprocess. Both read the same saved logical token
indices generated by the actual FlashMLA unit-test helper. See README.md for
pinned source revisions, installation, timing semantics, and memory requirements.
"""

from __future__ import annotations

import argparse
import ast
import csv
import hashlib
import importlib.metadata
import json
import os
import statistics
import subprocess
import sys
from pathlib import Path

PINNED_COMMITS = {
    "flashinfer": "d9c5811cf5530aa3969761847c0ee1399cff7f18",
    "flashmla": "2e5429fc5653bab6e081f09477126f731882a6a9",
}


def repo_info(path):
    def git(*args):
        return subprocess.check_output(["git", "-C", str(path), *args], text=True)

    diff = git("diff", "HEAD", "--ignore-submodules=all")
    return {
        "path": str(path),
        "commit": git("rev-parse", "HEAD").strip(),
        "tracked_diff_sha256": hashlib.sha256(diff.encode()).hexdigest(),
        "tracked_dirty": bool(diff),
        "submodules": git("submodule", "status", "--recursive").strip(),
    }


def file_sha256(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def case_shape(phase, quick):
    if quick:
        return (1, 129, 512) if phase == "prefill" else (4, 4, 512)
    return (1, 16384, 16384) if phase == "prefill" else (512, 4, 16384)


def load_indices(args, phase, topk, torch):
    batch, queries, context = case_shape(phase, args.quick)
    source_path = args.flashmla_repo / "tests/lib.py"
    source = source_path.read_text()
    helper = next(
        node
        for node in ast.parse(source).body
        if isinstance(node, ast.FunctionDef) and node.name == "_randperm_batch"
    )
    helper_sha = hashlib.sha256(
        ast.get_source_segment(source, helper).encode()
    ).hexdigest()
    path = (
        args.output
        / "indices"
        / f"{phase}_b{batch}_q{queries}_kv{context}_topk{topk}.pt"
    )
    expected_positions = torch.arange(
        context - queries, context, dtype=torch.int32
    ).repeat(batch)
    if not path.exists():
        # Execute the pinned helper itself, without importing unrelated test
        # fixtures. Generation is outside the timed attention graph.
        scope = {"torch": torch, "List": list}
        exec(
            compile(
                ast.Module(body=[helper], type_ignores=[]), str(source_path), "exec"
            ),
            scope,
        )
        torch.manual_seed(20261012 + topk)
        with torch.device("cuda"):
            indices = (
                scope["_randperm_batch"](
                    batch * queries, expected_positions.cuda() + 1, topk, [-1]
                )
                .contiguous()
                .cpu()
            )
        path.parent.mkdir(parents=True, exist_ok=True)
        torch.save(
            {
                "indices": indices,
                "positions": expected_positions,
                "sha256": hashlib.sha256(indices.numpy().tobytes()).hexdigest(),
                "helper_sha256": helper_sha,
            },
            path,
        )
    saved = torch.load(path, map_location="cpu", weights_only=True)
    indices = saved["indices"]
    digest = hashlib.sha256(indices.numpy().tobytes()).hexdigest()
    if (
        saved["helper_sha256"] != helper_sha
        or saved["sha256"] != digest
        or indices.shape != (batch * queries, topk)
        or indices.dtype != torch.int32
        or not torch.equal(saved["positions"], expected_positions)
    ):
        raise ValueError(f"Index file does not match this workload/helper: {path}")
    return indices.cuda(), expected_positions.cuda(), digest, helper_sha


def check_reference(q, kv, indices, output, scale, torch):
    """Check all heads of up to 73 representative query rows using FP32."""
    n, heads, dim = q.shape
    kv_heads = kv.shape[1]
    rows = set(torch.linspace(0, n - 1, min(n, 64)).long().tolist())
    rows.update(i for i in (0, 1, 2, 3, 127, 128, 511, 512, 2047, 2048, n - 1) if i < n)
    rows = sorted(rows)
    worst_rms, worst_abs, worst_cosine = 0.0, 0.0, 0.0
    for start in range(0, len(rows), 8):
        r = torch.tensor(rows[start : start + 8], device="cuda", dtype=torch.long)
        ids = indices[r].long()
        selected = (
            kv[ids.clamp_min(0)]
            .permute(0, 2, 1, 3)
            .reshape(-1, ids.shape[1], dim)
            .float()
        )
        query = q[r].reshape(-1, heads // kv_heads, dim).float()
        logits = torch.bmm(query, selected.transpose(1, 2)) * scale
        valid = (
            (ids >= 0)[:, None, :].expand(-1, kv_heads, -1).reshape(-1, ids.shape[1])
        )
        logits.masked_fill_(~valid[:, None, :], -torch.inf)
        reference = torch.bmm(logits.softmax(-1), selected).reshape(len(r), heads, dim)
        actual = output[r].float()
        diff = actual - reference
        rms = (
            (diff.square().mean() / reference.square().mean().clamp_min(1e-20))
            .sqrt()
            .item()
        )
        cosine = (
            1
            - torch.nn.functional.cosine_similarity(
                actual.flatten(), reference.flatten(), dim=0
            ).item()
        )
        if not (torch.isfinite(actual).all() and rms < 0.01 and cosine < 1e-5):
            raise AssertionError(
                f"FP32 reference failed: rows={r.tolist()}, rms={rms}, cosine={cosine}"
            )
        worst_rms = max(worst_rms, rms)
        worst_abs = max(worst_abs, diff.abs().max().item())
        worst_cosine = max(worst_cosine, cosine)
    return dict(
        sampled_queries=len(rows),
        heads_per_query=heads,
        worst_rms_relative=worst_rms,
        worst_abs=worst_abs,
        worst_cosine_error=worst_cosine,
    )


def measure(run, args, torch):
    for _ in range(5):
        run()
    torch.cuda.synchronize()
    graph = torch.cuda.CUDAGraph()
    with torch.cuda.graph(graph):
        output = run()

    def elapsed(replays):
        start, stop = (
            torch.cuda.Event(enable_timing=True),
            torch.cuda.Event(enable_timing=True),
        )
        start.record()
        for _ in range(replays):
            graph.replay()
        stop.record()
        stop.synchronize()
        return start.elapsed_time(stop)

    warmed_ms = 0.0
    while warmed_ms < args.warmup_ms:
        warmed_ms += elapsed(50)
    samples = [elapsed(args.replays) / args.replays for _ in range(args.samples)]
    return output, dict(
        median_ms=statistics.median(samples),
        min_ms=min(samples),
        max_ms=max(samples),
        samples_ms=samples,
        actual_warmup_ms=warmed_ms,
    )


def run_worker(args):
    sys.path[:0] = [str(args.flashinfer_repo), str(args.flashmla_repo)]
    import torch

    torch.set_num_threads(8)
    torch.cuda.set_device(0)
    if torch.cuda.get_device_capability() not in ((10, 0), (10, 3)):
        raise RuntimeError("The pinned comparison requires an SM100 or SM103 GPU")
    torch.backends.cuda.matmul.allow_tf32 = False
    phase, topk = args.phase[0], args.topk[0]
    batch, queries, context = case_shape(phase, args.quick)
    dim, heads, kv_heads = (256, 256, 2) if args.worker == "prims_ts" else (512, 128, 1)
    indices, positions, digest, helper_sha = load_indices(args, phase, topk, torch)
    requests = torch.arange(batch, device="cuda", dtype=torch.int32).repeat_interleave(
        queries
    )
    global_indices = torch.where(
        indices >= 0, indices + requests[:, None] * context, -1
    ).contiguous()
    torch.manual_seed(9012)
    q = torch.randn(batch * queries, heads, dim, device="cuda", dtype=torch.bfloat16)
    kv = torch.randn(
        batch * context, kv_heads, dim, device="cuda", dtype=torch.bfloat16
    )
    scale = dim**-0.5
    info = dict(
        backend=args.worker,
        phase=phase,
        batch=batch,
        q_len=queries,
        kv_len=context,
        topk=topk,
        heads_q=heads,
        heads_kv=kv_heads,
        head_dim=dim,
        dtype="bf16",
        shared_kv=True,
        indices_sha256=digest,
        helper_sha256=helper_sha,
        split_kv_allowed=args.split_kv if args.worker == "prims_ts" else None,
    )
    if args.worker == "prims_ts":
        import flashinfer
        from flashinfer.decode import (
            QTokenKvBlockSparsePagedTSWrapper,
            get_q_token_kv_block_sparse_workspace_size,
        )

        if not Path(flashinfer.__file__).resolve().is_relative_to(args.flashinfer_repo):
            raise RuntimeError("FlashInfer was not imported from --flashinfer-repo")
        page = 64
        cache = (
            kv.view(batch * context // page, page, kv_heads, dim)
            .permute(0, 2, 1, 3)
            .contiguous()
        )
        table = torch.arange(
            batch * context // page, device="cuda", dtype=torch.int32
        ).view(batch, context // page)
        query = q.view(batch, queries, 1, heads, dim)
        size = get_q_token_kv_block_sparse_workspace_size(
            query,
            cache,
            table,
            block_topk=topk,
            max_seq_len_kv=context,
            kv_block_size=1,
            split_kv=args.split_kv,
        )
        workspace = torch.zeros(size, device="cuda", dtype=torch.uint8)
        wrapper = QTokenKvBlockSparsePagedTSWrapper()
        wrapper.plan(
            batch_size=batch * queries,
            # This required upstream parameter denotes sparse group size G.
            seq_len_q=1,
            num_qo_heads=heads,
            num_kv_heads=kv_heads,
            head_dim=dim,
            kv_block_size=1,
            page_size=page,
            block_topk=topk,
            max_seq_len_kv=context,
            device=q.device,
            workspace_buffer=workspace,
            split_kv=args.split_kv,
            q_data_type=q.dtype,
            kv_data_type=q.dtype,
            o_data_type=q.dtype,
        )
        out = torch.empty_like(query)

        def run():
            return wrapper.run(
                query,
                (cache, cache),
                table,
                indices,
                requests,
                positions,
                out=out,
                sm_scale=scale,
            ).view_as(q)

        info.update(
            entry="QTokenKvBlockSparsePagedTSWrapper.run",
            workspace_bytes=size,
            module_path=flashinfer.__file__,
            cta_group=1,
        )
    else:
        import flash_mla
        import flash_mla.cuda

        if not Path(flash_mla.__file__).resolve().is_relative_to(args.flashmla_repo):
            raise RuntimeError(
                "FlashMLA was not imported from --flashmla-repo; install it editable"
            )
        shaped_indices = global_indices[:, None, :]

        def run():
            return flash_mla.flash_mla_sparse_fwd(
                q, kv, shaped_indices, scale, d_v=512
            )[0]

        info.update(
            entry="flash_mla_sparse_fwd (flattened B*Q)",
            cta_group=2,
            module_path=flash_mla.__file__,
            extension_path=flash_mla.cuda.__file__,
            extension_sha256=file_sha256(flash_mla.cuda.__file__),
        )
    with torch.inference_mode():
        output = run()
        torch.cuda.synchronize()
        if not torch.isfinite(output).all():
            raise AssertionError("Nonfinite output")
        info["reference_before"] = check_reference(
            q, kv, global_indices, output, scale, torch
        )
        output, times = measure(run, args, torch)
        info.update(times)
        info["reference_after"] = check_reference(
            q, kv, global_indices, output, scale, torch
        )
    pairs = int((indices >= 0).sum().item())
    info.update(valid_selected_pairs=pairs, useful_flops=4 * heads * dim * pairs)
    info["useful_tflops"] = info["useful_flops"] / (info["median_ms"] * 1e9)
    props = torch.cuda.get_device_properties(0)
    info["environment"] = dict(
        torch=torch.__version__,
        cuda=torch.version.cuda,
        cutlass_dsl=importlib.metadata.version("nvidia-cutlass-dsl"),
        gpu=props.name,
        gpu_uuid=str(props.uuid),
        sm_count=props.multi_processor_count,
        visible_devices=os.environ.get("CUDA_VISIBLE_DEVICES"),
        nvcc=subprocess.check_output(["nvcc", "--version"], text=True),
        gpu_state=subprocess.check_output(
            [
                "nvidia-smi",
                "--query-gpu=name,uuid,driver_version,power.limit,clocks.sm,clocks.mem",
                "--format=csv,noheader",
            ],
            text=True,
        ),
    )
    path = args.output / f"{phase}_topk{topk}_{args.worker}.json"
    path.write_text(json.dumps(info, indent=2) + "\n")
    print(f"{args.worker}: {phase} topk={topk}: {info['median_ms']:.6f} ms", flush=True)


def compare(args):
    args.output.mkdir(parents=True, exist_ok=True)
    # A failed rerun must not leave an old summary looking like its result.
    for name in ("comparison.csv", "comparison.json", "comparison.md"):
        (args.output / name).unlink(missing_ok=True)
    repositories = {
        name: repo_info(getattr(args, name + "_repo")) for name in PINNED_COMMITS
    }
    manifest = dict(
        repositories=repositories,
        pinned_commits=PINNED_COMMITS,
        script_sha256=file_sha256(__file__),
        split_kv=args.split_kv,
        quick=args.quick,
        phases=args.phase,
        topk=args.topk,
        timing=dict(
            warmup_ms=args.warmup_ms, samples=args.samples, replays=args.replays
        ),
    )
    (args.output / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    for name, repo in repositories.items():
        if repo["commit"] != PINNED_COMMITS[name] or repo["tracked_dirty"]:
            print(
                f"NOTE: {name} differs from the pinned clean source; see manifest.json",
                flush=True,
            )
    env = os.environ.copy()
    env.setdefault("FLASHINFER_WORKSPACE_BASE", str(args.output / "cache"))
    env.setdefault("CUTE_DSL_CACHE_DIR", str(args.output / "cache/cute_dsl"))
    results, rows = [], []
    for phase in args.phase:
        for topk in args.topk:
            pair = []
            for backend in ("prims_ts", "flashmla"):
                command = [
                    sys.executable,
                    str(Path(__file__).resolve()),
                    "--flashinfer-repo",
                    str(args.flashinfer_repo),
                    "--flashmla-repo",
                    str(args.flashmla_repo),
                    "--output",
                    str(args.output),
                    "--phase",
                    phase,
                    "--topk",
                    str(topk),
                    "--worker",
                    backend,
                    "--warmup-ms",
                    str(args.warmup_ms),
                    "--samples",
                    str(args.samples),
                    "--replays",
                    str(args.replays),
                ]
                if args.quick:
                    command.append("--quick")
                if not args.split_kv:
                    command.append("--no-split-kv")
                log_path = args.output / f"{phase}_topk{topk}_{backend}.log"
                print(
                    f"Running {phase} topk={topk} {backend}; log: {log_path}",
                    flush=True,
                )
                with log_path.open("w") as log:
                    subprocess.run(
                        command,
                        env=env,
                        stdout=log,
                        stderr=subprocess.STDOUT,
                        check=True,
                    )
                pair.append(json.loads(log_path.with_suffix(".json").read_text()))
            prims, mla = pair
            for key in (
                "indices_sha256",
                "helper_sha256",
                "valid_selected_pairs",
                "useful_flops",
            ):
                if prims[key] != mla[key]:
                    raise AssertionError(
                        f"Backends compared different workloads: {key}"
                    )
            results.extend(pair)
            rows.append(
                dict(
                    phase=phase,
                    batch=prims["batch"],
                    q_len=prims["q_len"],
                    kv_len=prims["kv_len"],
                    topk=topk,
                    prims_ts_d256_ms=prims["median_ms"],
                    flashmla_d512_ms=mla["median_ms"],
                    gap_percent=(prims["median_ms"] / mla["median_ms"] - 1) * 100,
                    prims_ts_tflops=prims["useful_tflops"],
                    flashmla_tflops=mla["useful_tflops"],
                    indices_sha256=prims["indices_sha256"],
                )
            )
    with (args.output / "comparison.csv").open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    (args.output / "comparison.json").write_text(
        json.dumps(dict(manifest=manifest, comparison=rows, cases=results), indent=2)
        + "\n"
    )
    table = [
        "| Phase | Top-k | PrimTS D256 (ms) | FlashMLA D512 (ms) | D256 gap |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for r in rows:
        table.append(
            f"| {r['phase']} | {r['topk']} | {r['prims_ts_d256_ms']:.3f} | {r['flashmla_d512_ms']:.3f} | {r['gap_percent']:+.1f}% |"
        )
    report = (
        "Quick validation shapes; not the full performance table.\n\n"
        if args.quick
        else ""
    )
    report += "\n".join(table) + "\n\nPositive gap means PrimTS D256 is slower.\n"
    (args.output / "comparison.md").write_text(report)
    print(report)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--flashinfer-repo", type=Path, required=True)
    parser.add_argument("--flashmla-repo", type=Path, required=True)
    parser.add_argument(
        "--output", type=Path, default=Path(__file__).resolve().parent / "results"
    )
    parser.add_argument(
        "--phase",
        choices=("prefill", "decode"),
        nargs="+",
        default=["prefill", "decode"],
    )
    parser.add_argument(
        "--topk", type=int, choices=(512, 2048), nargs="+", default=[512, 2048]
    )
    parser.add_argument(
        "--split-kv", action=argparse.BooleanOptionalAction, default=True
    )
    parser.add_argument(
        "--quick",
        action="store_true",
        help="Use small validation shapes instead of the full table",
    )
    parser.add_argument("--warmup-ms", type=float, default=200)
    parser.add_argument("--samples", type=int, default=9)
    parser.add_argument("--replays", type=int, default=20)
    parser.add_argument(
        "--worker", choices=("prims_ts", "flashmla"), help=argparse.SUPPRESS
    )
    args = parser.parse_args()
    if args.warmup_ms <= 0 or args.samples <= 0 or args.replays <= 0:
        parser.error("warmup-ms, samples, and replays must be positive")
    for key in ("flashinfer_repo", "flashmla_repo", "output"):
        setattr(args, key, getattr(args, key).resolve())
    if args.worker:
        run_worker(args)
    else:
        compare(args)


if __name__ == "__main__":
    main()
